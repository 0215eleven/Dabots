const assert=require('node:assert/strict');
const createChat=require('./create-chat.cjs');
module.exports=async function({page,h,visible,back,check,until,capture}){
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.locator('select').filter({has:page.locator('option[value="dark"]')}).selectOption('dark');
 await page.locator('select').filter({has:page.locator('option[value="zh"]')}).selectOption('zh');await back();
 await createChat(page,'添加机器人');
 const name=()=>page.getByLabel('机器人名称',{exact:true});
 const save=()=>page.getByRole('button',{name:'创建机器人',exact:true});
 await name().waitFor();await visible('Bot 需要一个名字').waitFor();
 await name().fill('  chief  ');await visible('已经有叫 chief 的 Bot 了').waitFor();assert.equal(await save().isDisabled(),true);
 await name().fill('@bad');await visible('Bot 名字里不能有 @、` 或换行').waitFor();assert.equal(await save().isDisabled(),true);
 check('required, invalid and duplicate names explain why creation is disabled');
 const before=(await h.call('state')).bots.length;
 await name().fill('创建提示验证');
 let rejection=400;
 const reject=async route=>{const request=route.request();if(request.method()!=='POST'||request.postDataJSON()?.endpoint!=='create-bot')return route.continue();await route.fulfill({status:rejection,contentType:'application/json',headers:{'access-control-allow-origin':new URL(page.url()).origin},body:JSON.stringify({error:{code:'CONTROLLED_FAILURE',message:'The computer has no default model.'}})});};
 await page.route('**/mobile/v1/actions',reject);await save().click();await visible('此电脑未设置默认模型。').waitFor();
 assert.equal(await name().inputValue(),'创建提示验证');assert.equal((await h.call('state')).bots.length,before);assert.equal(await save().isEnabled(),true);
 const error=await visible('此电脑未设置默认模型。').boundingBox();assert.ok(error.y>=0&&error.y<page.viewportSize().height,'failure is visible beside the submission action');
 await capture('create-rejected','zh');check('a controlled server rejection displays its precise Chinese reason and preserves the draft');
 await page.unroute('**/mobile/v1/actions',reject);await save().click();await visible('创建提示验证').waitFor();
 const created=(await h.call('state')).bots.filter(bot=>bot.name==='创建提示验证');assert.equal(created.length,1);assert.equal((await h.call('state')).bots.length,before+1);
 check('corrected retry creates exactly one Bot through the real public DSH host');
 await createChat(page,'添加机器人');await name().fill('未知结果验证');rejection=500;await page.route('**/mobile/v1/actions',reject);await save().click();
 await visible('未收到回复，修改可能已在电脑上生效。请刷新并检查后再进行其他修改。').waitFor();assert.equal(await save().isDisabled(),true);
 assert.equal((await h.call('state')).bots.length,before+1);await capture('create-uncertain','zh');check('an uncertain outcome explains the review requirement and blocks duplicate creation');
 await page.unroute('**/mobile/v1/actions',reject);
};
