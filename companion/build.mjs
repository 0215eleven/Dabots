import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
// bundleKey names the plugin-manager settings page the pairing UI attaches to:
// this standalone package, or `ds-bot` inside the single DS Bot package.
export async function bundleCompanion({ bundleKey = 'ds-bot-mobile-app' } = {}) {
  const result = await build({ entryPoints: [fileURLToPath(new URL('./src/client.mjs', import.meta.url))], bundle: true, format: 'cjs', platform: 'browser', target: 'es2022', external: ['react', 'react-dom'], loader: { '.css': 'text' }, define: { __DSMA_BUNDLE_KEY__: JSON.stringify(bundleKey) }, write: false, charset: 'utf8' })
  return result.outputFiles[0].text
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('./client.js', import.meta.url), `// Generated by build.mjs.
window.__ModuleLoader__.load({id:'ds-bot-mobile-app',factory:(require)=>{
const module={exports:{}};
${await bundleCompanion()}
return Object.defineProperty({...module.exports},Symbol.toStringTag,{value:'Module'});
}});
`)
  console.log('Built Mobile App companion')
}
