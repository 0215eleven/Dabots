import {createRequire} from 'node:module'
import {readFile,readdir,writeFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'
const require=createRequire(new URL('../bridge/package.json',import.meta.url))
const {build}=require('esbuild')
await build({entryPoints:[fileURLToPath(new URL('../../ios-app/sdk/relay-bridge-shared.js',import.meta.url))],outfile:fileURLToPath(new URL('../bridge/src/relay-shared.mjs',import.meta.url)),platform:'node',target:'node24',format:'esm',bundle:true,banner:{js:'/* oxlint-disable */\n// Generated by scripts/build-relay-bridge.mjs. Do not edit; Happy and dependency notices ship alongside.\nimport { createRequire as createBundleRequire } from "node:module";\nconst require = createBundleRequire(import.meta.url);'},legalComments:'inline'})
let notices=await readFile(new URL('../../ios-app/sdk/vendor/LICENSE.happy',import.meta.url),'utf8')
for(const name of ['tweetnacl','@noble/hashes','@stablelib/base64']){
 const dir=new URL(`../../ios-app/sdk/node_modules/${name}/`,import.meta.url)
 const file=(await readdir(dir)).find(x=>/^license(?:\.md|\.txt)?$/i.test(x))
 if(!file)throw Error(`License missing: ${name}`)
 notices+=`\n\nDependency: ${name}\n${await readFile(new URL(file,dir),'utf8')}`
}
await writeFile(new URL('../bridge/THIRD_PARTY_RELAY_NOTICES.txt',import.meta.url),notices)
