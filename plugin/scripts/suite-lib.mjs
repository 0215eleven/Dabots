// Composes the single DS Bot package: the owner's patched engine (unchanged), the
// Mobile Bridge as the `ds-bot/bridge` row, and the pairing UI merged into the
// engine's one client module. DSH reads one `./client` per package and attaches it
// to the bare package row only (dsh-client-modules resolveMeta/locatePkgJson).
import {cp,mkdir,readFile,writeFile} from 'node:fs/promises'
import {join,relative,sep} from 'node:path'

export const BRIDGE_ROW='ds-bot-mobile-bridge'
// Bridge contract v1 (docs/version-sources.md): capabilities, not version numbers.
const CONTRACT=['bridge.describe','bridge.submit','bridge.redact']

// The generated client is `window.__ModuleLoader__.load({ id, factory: <fn> })`;
// return the factory expression so a new module can call it.
export function extractFactory(source,id){
  const head=new RegExp(String.raw`window\.__ModuleLoader__\.load\(\{\s*id:\s*(['"])${id.replace(/[.*+?^${}()|[\]\\-]/g,'\\$&')}\1,\s*factory:\s*`)
  const match=head.exec(source)
  if(!match||source.indexOf('window.__ModuleLoader__.load(',match.index+1)!==-1)throw Error(`Expected exactly one ${id} client registration`)
  const tail=/,?\s*\}\)\s*;?\s*$/.exec(source)
  if(!tail||tail.index<=match.index+match[0].length)throw Error(`Unrecognized ${id} client wrapper`)
  return source.slice(match.index+match[0].length,tail.index)
}

// One module, one registration. The mobile UI is isolated so a failure there
// never takes the Bot team UI down with it.
export function composeClient({engineClient,mobileBundle,id='ds-bot'}){
  const factory=extractFactory(engineClient,id)
  return `// Generated by scripts/pack-suite.mjs: Dabots client + mobile connection settings.
window.__ModuleLoader__.load({id:${JSON.stringify(id)},factory:(require)=>{
const engine=(${factory})(require);
const mobile=(()=>{const module={exports:{}};
${mobileBundle}
return module.exports})();
const inject=[...new Set([...(engine.inject??[]),...(mobile.inject??[])])];
function apply(ctx,config){
engine.apply(ctx,config);
try{mobile.apply(ctx,config)}catch(error){console.error('[ds-bot] mobile connection settings unavailable',error)}
}
return Object.defineProperty({...engine,inject,apply},Symbol.toStringTag,{value:'Module'});
}});
`
}

// Keeps the engine patch verbatim and adds the Bridge row under its existing ID,
// so owner overrides, the dedicated Bridge home and device pairings carry over.
export function composePatch({enginePatch,bridgePatch,packageName='ds-bot'}){
  const rows=bridgePatch.match(new RegExp(String.raw`^\s*-\s*id:\s*${BRIDGE_ROW}\s*$`,'gm'))??[]
  const names=bridgePatch.match(new RegExp(String.raw`^\s*name:\s*${BRIDGE_ROW}\s*$`,'gm'))??[]
  if(rows.length!==1||names.length!==1)throw Error('Bridge patch must insert exactly one ds-bot-mobile-bridge row')
  if(new RegExp(String.raw`id:\s*${BRIDGE_ROW}\b`).test(enginePatch))throw Error('Engine patch already declares the Bridge row')
  return `${enginePatch.trimEnd()}\n\n# Mobile Bridge, merged into this package. The row ID is unchanged from the\n# standalone ds-bot-mobile-bridge bundle so existing owner configuration applies.\n${bridgePatch.replace(new RegExp(String.raw`^(\s*name:\s*)${BRIDGE_ROW}\s*$`,'m'),`$1${packageName}/bridge`).trimEnd()}\n`
}

export function engineContract(channelSource){
  const missing=CONTRACT.filter(name=>!channelSource.includes(`'${name}'`)&&!channelSource.includes(`"${name}"`))
  return {missing,agents:/['"]bridge\.agent-(open|new)['"]/.test(channelSource)}
}

const merge=(label,a={},b={})=>{
  for(const [key,value] of Object.entries(b))if(key in a&&a[key]!==value)throw Error(`${label} conflict for ${key}: ${a[key]} vs ${value}`)
  return {...a,...b}
}

// Builds the manifest from the engine's own manifest; everything the engine
// declares is kept, the Bridge adds an export, files and its runtime dependency.
export function composeManifest({engine,bridge,version,suite}){
  if(engine.name!=='ds-bot')throw Error('The engine must be the ds-bot package')
  if(engine.type!=='module')throw Error('The engine must be an ES module package')
  if(engine.exports?.['./bridge'])throw Error('The engine already exports ./bridge')
  return {
    ...engine,
    version,
    description:'Dabots — the DSH Bot team, Mobile Bridge and phone connection settings in one plugin',
    homepage:'https://github.com/0215eleven/Dabots#readme',
    repository:{type:'git',url:'git+https://github.com/0215eleven/Dabots.git',directory:'plugin/engine'},
    bugs:{url:'https://github.com/0215eleven/Dabots/issues'},
    exports:{...engine.exports,'./bridge':'./bridge/index.mjs'},
    files:[...new Set([...(engine.files??[]),'bridge/','docs/','SUITE.md','NOTICE','THIRD_PARTY_BLOUB_LICENSE.txt'])],
    dependencies:merge('dependency',engine.dependencies,bridge.dependencies),
    peerDependencies:merge('peer dependency',engine.peerDependencies,bridge.peerDependencies),
    dsBotSuite:suite,
  }
}

const skip=item=>item.split(sep).some(part=>part==='node_modules'||part==='.git')
// Copies only the Bridge's declared files; the engine is copied whole and its
// manifest `files` decides what npm pack ships.
export async function stageBridge({bridgeDir,target}){
  const manifest=JSON.parse(await readFile(join(bridgeDir,'package.json'),'utf8'))
  await mkdir(join(target,'bridge'),{recursive:true})
  for(const file of manifest.files){
    if(file.endsWith('/')||file.includes('..'))throw Error(`Unexpected bridge file entry ${file}`)
    await mkdir(join(target,'bridge',file,'..'),{recursive:true})
    await cp(join(bridgeDir,file),join(target,'bridge',file))
  }
  // Module scope for the .js sources without a second package identity.
  await writeFile(join(target,'bridge','package.json'),JSON.stringify({type:'module',private:true},null,2)+'\n')
  return manifest
}
export async function stageEngine({engineDir,target}){
  await cp(engineDir,target,{recursive:true,filter:item=>!skip(relative(engineDir,item))})
}
